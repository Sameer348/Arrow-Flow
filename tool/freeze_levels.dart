// Regenerates lib/game/levels/curated_levels.dart.
//
// Levels 1–3 are hand-authored tutorials. Levels 4–50 are curated from
// hand-picked generator configurations and frozen to data so they never
// change if the generator evolves. Run:  dart run tool/freeze_levels.dart
import 'dart:io';

import 'package:arrow_flow/core/utils/seeded_random.dart';
import 'package:arrow_flow/game/board/board_state.dart';
import 'package:arrow_flow/game/generator/level_generator.dart';
import 'package:arrow_flow/game/solver/puzzle_solver.dart';
import 'package:arrow_flow/models/board_shape.dart';
import 'package:arrow_flow/models/level_data.dart';

const handmade = <(int, int, String)>[
  // rows/cols, arrows. Teaches: tap the free arrow, then the one it freed.
  (3, 3, '1,2,R,1;1,1,R,2'),
  (3, 3, '0,0,U,1;1,0,U,2;2,1,L,2;0,2,U,2'),
  (3, 3, '0,2,R,3;1,1,U,1;1,0,L,1;2,2,D,2;2,1,R,2'),
];

(int, Difficulty, BoardShape, double, int) configFor(int n) {
  if (n <= 6) return (3, Difficulty.tutorial, BoardShape.square, 0.85, 3);
  if (n <= 10) return (4, Difficulty.tutorial, BoardShape.square, 0.8, 3);
  if (n <= 15) return (4, Difficulty.easy, BoardShape.square, 0.85, 3);
  if (n <= 20) return (5, Difficulty.easy, BoardShape.square, 0.8, 4);
  if (n <= 27) return (5, Difficulty.normal, BoardShape.square, 0.85, 4);
  if (n <= 35) return (6, Difficulty.normal, BoardShape.square, 0.82, 4);
  if (n <= 40) return (7, Difficulty.hard, BoardShape.square, 0.82, 4);
  if (n <= 45) return (7, Difficulty.hard, BoardShape.square, 0.88, 5);
  const shapes = [BoardShape.heart, BoardShape.diamond, BoardShape.star, BoardShape.butterfly, BoardShape.crown];
  return (8, Difficulty.expert, shapes[n - 46], 0.88, 5);
}

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/freeze_levels.dart — do not edit by hand.')
    ..writeln('// Levels 1–3 hand-authored; 4–50 curated generator output, frozen.')
    ..writeln("import '../../models/board_shape.dart';")
    ..writeln("import '../../models/level_data.dart';")
    ..writeln()
    ..writeln('abstract final class CuratedLevels {')
    ..writeln('  static const int count = 50;')
    ..writeln()
    ..writeln('  static LevelData level(int n) {')
    ..writeln('    final e = _data[n - 1];')
    ..writeln('    return LevelData(')
    ..writeln('      id: n,')
    ..writeln('      rows: e.\$1,')
    ..writeln('      cols: e.\$1,')
    ..writeln('      difficulty: e.\$2,')
    ..writeln('      shape: e.\$3,')
    ..writeln('      mask: e.\$3.mask(e.\$1, e.\$1),')
    ..writeln('      starRequirements: StarRequirements(maxMistakesForTwo: e.\$4 < 10 ? 1 : 2, parSeconds: e.\$5),')
    ..writeln('      arrows: LevelData.decodeArrows(e.\$6),')
    ..writeln('    );')
    ..writeln('  }')
    ..writeln()
    ..writeln('  // (size, difficulty, shape, arrowCount, parSeconds, arrows)')
    ..writeln('  static const _data = <(int, Difficulty, BoardShape, int, int, String)>[');

  for (var n = 1; n <= 50; n++) {
    LevelData level;
    if (n <= handmade.length) {
      final h = handmade[n - 1];
      level = LevelData(id: n, rows: h.$1, cols: h.$2, arrows: LevelData.decodeArrows(h.$3), difficulty: Difficulty.tutorial,
          starRequirements: const StarRequirements(parSeconds: 15));
    } else {
      final (size, diff, shape, density, maxLen) = configFor(n);
      level = LevelGenerator.generate(
        GeneratorConfig(
          seed: SeededRandom.hashString('curated:$n'),
          rows: size, cols: size, difficulty: diff, density: density, shape: shape, maxLength: maxLen),
        levelId: n,
      );
    }
    final solve = PuzzleSolver.solve(BoardState.fromLevel(level));
    if (!solve.solvable) throw StateError('Level $n unsolvable');
    stderr.writeln('L$n ${level.rows}x${level.cols} ${level.shape.name} arrows=${level.arrows.length} depth=${solve.depth} avg=${solve.averageMoves.toStringAsFixed(1)}');
    out.writeln("    ($n == $n ? ${level.rows} : 0, Difficulty.${level.difficulty.name}, BoardShape.${level.shape.name}, ${level.arrows.length}, ${level.starRequirements.parSeconds}, '${level.encodeArrows()}'),");
  }
  out
    ..writeln('  ];')
    ..writeln('}');
  File('lib/game/levels/curated_levels.dart').writeAsStringSync(out.toString().replaceAll(RegExp(r'\(\d+ == \d+ \? '), '(').replaceAll(RegExp(r' : 0, Difficulty'), ', Difficulty'));
}
